export const riskHeatmap: { hour: number; day: number; value: number }[] = (() => {
  const rng = makeRng(7174);
  const out: { hour: number; day: number; value: number }[] = [];
  for (let d = 0; d < 7; d++) {
    for (let h = 0; h < 24; h++) {
      const base =
        (Math.sin(h / 3 - 1) + 1) * 0.5 * 0.7 +
        (d === 1 || d === 4 ? 0.2 : 0) +
        (h >= 9 && h <= 17 ? 0.25 : 0);
      const v = Math.min(1, Math.max(0, base + (rng() - 0.5) * 0.25));
      out.push({ hour: h, day: d, value: v });
    }
  }
  return out;
})();

